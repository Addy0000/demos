"use client";

import { useReport } from "@/components/report/report-context";
import { useTenant } from "@/components/appearance";
import { BrandMark } from "@/components/brand";

const KIND_LABEL = { report: "Report", document: "Document", page: "Printout" } as const;

function stampTime(d: Date): string {
  return d.toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
    timeZone: "Asia/Kolkata",
  });
}

/**
 * Print-only letterhead and running footer. Invisible on screen; on paper it
 * heads every generated report and document. Screens that already draw their
 * own statutory letterhead (credit note, proforma, debit note, journal voucher,
 * packing list) mark themselves `data-print-document`, and CSS drops this one.
 */
export function PrintLetterhead() {
  const { stamp, user } = useReport();
  const COMPANY = useTenant();
  if (!stamp) return null;

  return (
    <>
      <div data-print-letterhead className="hidden print:block">
        <div className="flex items-end justify-between border-b-2 border-ink pb-2">
          <div>
            <p className="text-[15px] font-semibold leading-tight tracking-tight text-ink">{COMPANY.name}</p>
            <p className="text-[9.5px] text-muted">{COMPANY.descriptor}</p>
          </div>
          <BrandMark tenant={COMPANY.key} size={30} accent="var(--primary)" className="text-ink" />
        </div>

        <div className="flex items-start justify-between gap-6 border-b border-edge py-3">
          <div className="min-w-0">
            <h1 className="text-[19px] font-semibold leading-tight tracking-tight text-ink">
              {stamp.code ? <span className="mr-2 font-num text-[13px] font-medium text-muted">{stamp.code}</span> : null}
              {stamp.title}
            </h1>
            {stamp.rowCount !== null && (
              <p className="mt-1 text-[10px] text-muted">
                {stamp.rowCount.toLocaleString("en-IN")} record{stamp.rowCount === 1 ? "" : "s"} in the filter at the time of generation
              </p>
            )}
          </div>
          <dl className="grid shrink-0 grid-cols-[auto_auto] gap-x-3 gap-y-0.5 text-[9.5px]">
            <dt className="text-muted">Type</dt>
            <dd className="font-medium text-ink">{KIND_LABEL[stamp.kind]}</dd>
            <dt className="text-muted">No.</dt>
            <dd className="font-num font-medium text-ink">{stamp.number}</dd>
            <dt className="text-muted">Generated</dt>
            <dd className="font-num text-ink">{stampTime(stamp.generatedAt)} IST</dd>
            <dt className="text-muted">By</dt>
            <dd className="text-ink">
              {user.name} · {user.roleLabel}
            </dd>
            <dt className="text-muted">Source</dt>
            <dd className="font-num text-ink">{stamp.path}</dd>
          </dl>
        </div>
      </div>

      <div data-print-footer className="hidden print:flex">
        <span>Computer-generated by {COMPANY.name}. No signature required unless stated.</span>
        <span className="font-num">{stamp.number}</span>
      </div>
    </>
  );
}
